import {test} from 'node:test';
import assert from 'node:assert/strict';
import {PGlite} from '@electric-sql/pglite';
import {createHandler} from '../api/chat.js';
test('family authentication, persistence, isolation and logout',async()=>{
 const db=new PGlite();
 function sql(parts,...values){const query=parts.reduce((s,p,i)=>s+(i?'$'+i:'')+p,'');return {then(resolve,reject){return db.query(query,values).then(r=>r.rows).then(resolve,reject);},query,values};}
 sql.transaction=queries=>db.transaction(async tx=>{const results=[];for(const q of queries)results.push((await tx.query(q.query,q.values)).rows);return results;});
 process.env.DATABASE_URL='postgresql://test-only';
 const handler=createHandler(()=>sql);let requestNumber=0;
 async function call(body,cookie='',origin='https://family.test',query={}){
 const result={status:200,headers:{}};const res={setHeader(k,v){result.headers[k]=v;},status(n){result.status=n;return this;},json(data){result.data=data;return this;},end(bytes){result.bytes=bytes;return this;}};
 await handler({method:body?'POST':'GET',body,query,headers:{host:'family.test',origin,cookie,'x-forwarded-for':'192.0.2.'+(++requestNumber)}},res);
 result.cookie=result.headers['Set-Cookie']?.split(';')[0];return result;
 }
 assert.equal((await call()).status,401);
 const father=await call({action:'create',username:'father',name:'Pai',password:'correct-password'});assert.equal(father.status,200);assert.match(father.data.invite,/^[0-9a-z]{10}$/);
 assert.match(father.headers['Set-Cookie'],/HttpOnly; Secure; SameSite=Lax/);
 assert.equal((await call({action:'join',username:'child',name:'Filha',password:'child-password',invite:'wrong'})).status,400);
 const child=await call({action:'join',username:'child',name:'Filha',password:'child-password',invite:father.data.invite.slice(0,5).toUpperCase()+' - '+father.data.invite.slice(5).toUpperCase()});assert.equal(child.status,200);
 await call({action:'send',body:'Oi, filha!'},father.cookie);
 assert.equal((await call(null,child.cookie)).data.messages[0].body,'Oi, filha!');
 await call({action:'send',body:'Oi, pai!'},child.cookie);
 assert.equal((await call(null,father.cookie)).data.messages.length,2);
 const other=await call({action:'create',username:'other',name:'Outro',password:'other-password'});
 assert.equal((await call(null,other.cookie)).data.messages.length,0);
 assert.equal((await call({action:'send',body:'invasão'},father.cookie,'https://evil.test')).status,403);
 assert.equal((await call({action:'login',username:'father',password:'wrong-password'})).status,401);
 assert.equal((await call({action:'login',username:'father',password:'correct-password'})).status,200);
 assert.equal((await call({action:'send',body:'a'.repeat(2001)},father.cookie)).status,400);
 await call({action:'logout'},child.cookie);assert.equal((await call(null,child.cookie)).status,401);
 const rotated=await call({action:'invite'},father.cookie);assert.match(rotated.data.invite,/^[0-9a-z]{10}$/);
 assert.equal((await call({action:'invite'})).status,401);
 assert.equal((await call({action:'join',username:'oldcode',name:'Outro',password:'other-password',invite:father.data.invite})).status,400);
 assert.equal((await call({action:'join',username:'newcode',name:'Outro',password:'other-password',invite:rotated.data.invite})).status,200);
 assert.equal((await call({action:'pin',current:'wrong-password',pin:'1234'},father.cookie)).status,401);
 assert.equal((await call({action:'pin',current:'correct-password',pin:'abc4'},father.cookie)).status,400);
 assert.equal((await call({action:'pin',current:'correct-password',pin:'0123'},father.cookie)).status,200);
 const pinLogin=await call({action:'login',username:'father',password:'0123'});assert.equal(pinLogin.status,200);
 assert.equal((await call({action:'login',username:'father',password:'correct-password'})).status,401);
 for(let i=0;i<4;i++)assert.equal((await call({action:'login',username:'father',password:'9999'})).status,401);
 assert.equal((await call({action:'login',username:'father',password:'0123'})).status,429);
 const pinFamily=await call({action:'create',username:'pinuser',name:'PIN',password:'0456'});assert.equal(pinFamily.status,200);
 assert.equal((await call({action:'login',username:'pinuser',password:'0456'})).status,200);
 const prior=await call(null,father.cookie);const before=String(prior.data.messages.at(-1).id);
 await call({action:'send',body:'Outra família'},other.cookie);
 await call({action:'send',body:'Mensagem nova'},father.cookie);
 assert.equal((await call({action:'clear',before,confirm:true})).status,401);
 assert.equal((await call({action:'clear',before},father.cookie)).status,400);
 assert.equal((await call(null,father.cookie)).data.messages.length,3);
 const cleared=await call({action:'clear',before,confirm:true},father.cookie);
 assert.equal(cleared.status,200);assert.deepEqual(cleared.data.messages.map(m=>m.body),['Mensagem nova']);
 assert.equal((await call(null,other.cookie)).data.messages[0].body,'Outra família');
 assert.equal((await call(null,father.cookie)).data.messages.length,1);
 const childAgain=await call({action:'login',username:'child',password:'child-password'});
 const third=await call({action:'login',username:'newcode',password:'other-password'});
 const roster=await call(null,father.cookie);assert.ok(roster.data.members.some(m=>m.id===child.data.user.id));assert.ok(!roster.data.members.some(m=>m.id===other.data.user.id));assert.ok(roster.data.members.every(m=>Object.keys(m).sort().join(',')==='id,name'));
 const privateSent=await call({action:'send',recipient:child.data.user.id,body:'Só para minha filha'},father.cookie);assert.equal(privateSent.status,200);
 const privateRead=await call({action:'load',recipient:father.data.user.id},childAgain.cookie);assert.deepEqual(privateRead.data.messages.map(m=>m.body),['Só para minha filha']);
 assert.ok(!(await call(null,father.cookie)).data.messages.some(m=>m.body==='Só para minha filha'));
 assert.equal((await call({action:'load',recipient:father.data.user.id},third.cookie)).data.messages.length,0);
 assert.equal((await call({action:'load',recipient:child.data.user.id},other.cookie)).status,403);
 assert.equal((await call({action:'send',recipient:child.data.user.id,body:'Invasão'},other.cookie)).status,403);
 const privateId=String(privateRead.data.messages[0].id);
 await call({action:'clear',recipient:father.data.user.id,before:privateId,confirm:true},third.cookie);
 assert.equal((await call({action:'load',recipient:father.data.user.id},childAgain.cookie)).data.messages.length,1);
 await call({action:'clear',recipient:child.data.user.id,before:privateId,confirm:true},father.cookie);
 assert.equal((await call({action:'load',recipient:father.data.user.id},childAgain.cookie)).data.messages.length,0);
 assert.equal((await call(null,father.cookie)).data.messages[0].body,'Mensagem nova');
 const audio={type:'audio/webm',data:Buffer.from([0x1a,0x45,0xdf,0xa3,1,2,3,4]).toString('base64')};
 const sentAudio=await call({action:'send',recipient:child.data.user.id,audio},father.cookie);assert.equal(sentAudio.status,200);
 const audioId=String(sentAudio.data.messages.at(-1).id);assert.equal(sentAudio.data.messages.at(-1).audio_type,'audio/webm');assert.equal(sentAudio.data.messages.at(-1).audio_data,undefined);
 const heard=await call(null,childAgain.cookie,'https://family.test',{audio:audioId});assert.equal(heard.status,200);assert.equal(heard.headers['Content-Type'],'audio/webm');assert.equal(heard.bytes.toString('base64'),audio.data);
 assert.equal((await call(null,third.cookie,'https://family.test',{audio:audioId})).status,404);
 assert.equal((await call(null,other.cookie,'https://family.test',{audio:audioId})).status,404);
 assert.equal((await call(null,'','https://family.test',{audio:audioId})).status,401);
 assert.equal((await call({action:'send',audio:{type:'audio/webm',data:'YWJjZA=='}},father.cookie)).status,400);
 assert.equal((await call({action:'send',audio:{type:'text/html',data:audio.data}},father.cookie)).status,400);
 assert.equal((await call({action:'send',audio:{type:'audio/webm',data:'A'.repeat(1398108)}},father.cookie)).status,400);
 await call({action:'clear',recipient:child.data.user.id,before:audioId,confirm:true},father.cookie);
 assert.equal((await call(null,childAgain.cookie,'https://family.test',{audio:audioId})).status,404);
 await db.close();
});
